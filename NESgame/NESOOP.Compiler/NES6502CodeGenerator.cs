using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace NESOOP.Compiler
{
    public sealed class Nes6502CodeGenerator
    {
        private const string ExpressionTemp =
            "__nesoop_expr_temp";

        private int _labelCounter = 0;


        public string Generate(
            SemanticProgram program
        )
        {
            _labelCounter = 0;

            StringBuilder output =
                new();


            output.AppendLine(
                "; =========================================================="
            );

            output.AppendLine(
                "; GENERATED BY NESOOP.Compiler"
            );

            output.AppendLine(
                "; DO NOT EDIT MANUALLY"
            );

            output.AppendLine(
                "; =========================================================="
            );

            output.AppendLine();


            // =========================================================
            // RAM
            // =========================================================

            output.AppendLine(
                ".segment \"BSS\""
            );

            output.AppendLine();


            // General expression temporary.
            output.AppendLine(
                $"{ExpressionTemp}: .res 1"
            );


            // ---------------------------------------------------------
            // Method parameters
            // ---------------------------------------------------------

            foreach (
                SemanticParameter parameter
                in program.Methods.SelectMany(
                    method => method.Parameters
                )
            )
            {
                output.AppendLine(
                    $"{parameter.StorageName}: .res 1"
                );
            }


            // ---------------------------------------------------------
            // Local variables
            //
            // Includes variables declared inside if/else blocks.
            // ---------------------------------------------------------

            foreach (
                SemanticVariableDeclaration variable
                in program.Methods
                    .SelectMany(
                        method =>
                            EnumerateStatements(
                                method.Statements
                            )
                    )
                    .OfType<SemanticVariableDeclaration>()
            )
            {
                output.AppendLine(
                    $"{variable.StorageName}: .res 1"
                );
            }


            output.AppendLine();


            // =========================================================
            // CODE
            // =========================================================

            output.AppendLine(
                ".segment \"CODE\""
            );

            output.AppendLine();


            // ---------------------------------------------------------
            // NES runtime imports
            // ---------------------------------------------------------

            foreach (
                NesBuiltInMethodDefinition builtIn
                in NesBuiltIns.AllMethods
            )
            {
                output.AppendLine(
                    $".import {builtIn.RuntimeLabel}"
                );


                foreach (
                    NesBuiltInParameterDefinition parameter
                    in builtIn.Parameters
                )
                {
                    output.AppendLine(
                        $".import {parameter.StorageName}"
                    );
                }
            }


            output.AppendLine();


            // Handwritten main.s calls this.
            output.AppendLine(
                ".export Game_Start"
            );

            output.AppendLine();


            // =========================================================
            // Generate methods
            // =========================================================

            foreach (
                SemanticMethod method
                in program.Methods
            )
            {
                GenerateMethod(
                    output,
                    method
                );
            }


            return output.ToString();
        }


        // =============================================================
        // Recursively enumerate statements
        //
        // Required because locals can now exist inside:
        //
        // if (...)
        // {
        //     byte thing = ...
        // }
        // =============================================================

        private static IEnumerable<SemanticStatement>
            EnumerateStatements(
                IEnumerable<SemanticStatement> statements
            )
        {
            foreach (
                SemanticStatement statement
                in statements
            )
            {
                yield return statement;


                if (
                    statement
                    is SemanticIfStatement ifStatement
                )
                {
                    foreach (
                        SemanticStatement nested
                        in EnumerateStatements(
                            ifStatement.ThenStatements
                        )
                    )
                    {
                        yield return nested;
                    }


                    foreach (
                        SemanticStatement nested
                        in EnumerateStatements(
                            ifStatement.ElseStatements
                        )
                    )
                    {
                        yield return nested;
                    }
                }
            }
        }


        // =============================================================
        // Method
        // =============================================================

        private void GenerateMethod(
            StringBuilder output,
            SemanticMethod method
        )
        {
            output.AppendLine(
                "; ----------------------------------------------------------"
            );

            output.AppendLine(
                $"; {method.ClassName}.{method.Name}()"
            );

            output.AppendLine(
                "; ----------------------------------------------------------"
            );


            output.AppendLine(
                $".proc {method.Label}"
            );

            output.AppendLine();


            foreach (
                SemanticStatement statement
                in method.Statements
            )
            {
                GenerateStatement(
                    output,
                    statement
                );
            }


            // A direct return statement already produced RTS.
            //
            // If the final statement is an if/else whose branches
            // both return, this extra RTS is unreachable but harmless.
            if (
                method.Statements.Count == 0 ||
                method.Statements[^1]
                    is not SemanticReturnStatement
            )
            {
                output.AppendLine(
                    "    rts"
                );
            }


            output.AppendLine();

            output.AppendLine(
                ".endproc"
            );

            output.AppendLine();
        }


        // =============================================================
        // Statements
        // =============================================================

        private void GenerateStatement(
            StringBuilder output,
            SemanticStatement statement
        )
        {
            // =========================================================
            // Variable declaration
            //
            // byte x = ...
            // bool x = ...
            //
            // Both occupy one byte on the NES.
            // =========================================================

            if (
                statement
                is SemanticVariableDeclaration variable
            )
            {
                output.AppendLine(
                    $"    ; {variable.Type} {variable.Name}"
                );


                GenerateLoadValue(
                    output,
                    variable.Initializer
                );


                output.AppendLine(
                    $"    sta {variable.StorageName}"
                );

                output.AppendLine();

                return;
            }


            // =========================================================
            // Variable assignment
            // =========================================================

            if (
                statement
                is SemanticVariableAssignment assignment
            )
            {
                GenerateLoadValue(
                    output,
                    assignment.Value
                );


                output.AppendLine(
                    $"    sta {assignment.StorageName}"
                );

                output.AppendLine();

                return;
            }


            // =========================================================
            // NES built-in property
            // =========================================================

            if (
                statement
                is SemanticBuiltInAssignment builtIn
            )
            {
                GenerateBuiltInAssignment(
                    output,
                    builtIn
                );

                return;
            }


            // =========================================================
            // Method-call statement
            // =========================================================

            if (
                statement
                is SemanticMethodCallStatement call
            )
            {
                GenerateCall(
                    output,
                    call.Call
                );

                output.AppendLine();

                return;
            }


            // =========================================================
            // Return
            // =========================================================

            if (
                statement
                is SemanticReturnStatement returnStatement
            )
            {
                if (returnStatement.Value != null)
                {
                    // Return byte/bool in A.
                    GenerateLoadValue(
                        output,
                        returnStatement.Value
                    );
                }


                output.AppendLine(
                    "    rts"
                );

                output.AppendLine();

                return;
            }


            // =========================================================
            // if / else
            // =========================================================

            if (
                statement
                is SemanticIfStatement ifStatement
            )
            {
                GenerateIf(
                    output,
                    ifStatement
                );

                return;
            }


            throw new Exception(
                "Internal compiler error: " +
                $"unknown semantic statement " +
                $"'{statement.GetType().Name}'."
            );
        }


        // =============================================================
        // IF / ELSE
        // =============================================================

        private void GenerateIf(
            StringBuilder output,
            SemanticIfStatement statement
        )
        {
            string thenLabel =
                NextLabel("if_then");

            string elseLabel =
                NextLabel("if_else");

            string endLabel =
                NextLabel("if_end");


            output.AppendLine(
                "    ; if condition"
            );


            // Bool result goes into A:
            //
            // false = 0
            // true  = 1
            GenerateLoadValue(
                output,
                statement.Condition
            );


            output.AppendLine(
                "    cmp #$00"
            );


            // ---------------------------------------------------------
            // Important NES/6502 detail:
            //
            // Conditional branches only have a short range.
            //
            // Therefore DON'T do:
            //
            //     beq some_far_away_else_block
            //
            // Instead branch to a nearby label and use JMP for
            // the potentially long distance.
            // ---------------------------------------------------------

            output.AppendLine(
                $"    bne {thenLabel}"
            );

            output.AppendLine(
                $"    jmp {elseLabel}"
            );


            // ---------------------------------------------------------
            // THEN
            // ---------------------------------------------------------

            output.AppendLine(
                $"{thenLabel}:"
            );


            foreach (
                SemanticStatement nested
                in statement.ThenStatements
            )
            {
                GenerateStatement(
                    output,
                    nested
                );
            }


            output.AppendLine(
                $"    jmp {endLabel}"
            );


            // ---------------------------------------------------------
            // ELSE
            // ---------------------------------------------------------

            output.AppendLine(
                $"{elseLabel}:"
            );


            foreach (
                SemanticStatement nested
                in statement.ElseStatements
            )
            {
                GenerateStatement(
                    output,
                    nested
                );
            }


            // ---------------------------------------------------------
            // END
            // ---------------------------------------------------------

            output.AppendLine(
                $"{endLabel}:"
            );

            output.AppendLine();
        }


        // =============================================================
        // NES built-in properties
        // =============================================================

        private void GenerateBuiltInAssignment(
            StringBuilder output,
            SemanticBuiltInAssignment assignment
        )
        {
            switch (assignment.Member)
            {
                // =====================================================
                // Screen.BackgroundColor
                // =====================================================

                case NesBuiltInMember.ScreenBackgroundColor:

                    output.AppendLine(
                        "    ; Screen.BackgroundColor"
                    );


                    // Reset PPU address latch.
                    output.AppendLine(
                        "    lda $2002"
                    );

                    output.AppendLine();


                    // Address $3F00
                    output.AppendLine(
                        "    lda #$3F"
                    );

                    output.AppendLine(
                        "    sta $2006"
                    );

                    output.AppendLine();


                    output.AppendLine(
                        "    lda #$00"
                    );

                    output.AppendLine(
                        "    sta $2006"
                    );

                    output.AppendLine();


                    GenerateLoadValue(
                        output,
                        assignment.Value
                    );


                    // NES palette index = six bits.
                    output.AppendLine(
                        "    and #$3F"
                    );


                    output.AppendLine(
                        "    sta $2007"
                    );

                    output.AppendLine();

                    return;


                default:

                    throw new Exception(
                        $"Internal compiler error: " +
                        $"NES built-in '{assignment.Member}' " +
                        $"has no code generator."
                    );
            }
        }


        // =============================================================
        // Expressions
        //
        // Result always ends up in accumulator A.
        // =============================================================

        private void GenerateLoadValue(
            StringBuilder output,
            SemanticValue value
        )
        {
            switch (value)
            {
                // -----------------------------------------------------
                // byte literal
                // -----------------------------------------------------

                case SemanticByteLiteral literal:

                    output.AppendLine(
                        $"    lda #${literal.Value:X2}"
                    );

                    return;


                // -----------------------------------------------------
                // bool literal
                //
                // false = 0
                // true  = 1
                // -----------------------------------------------------

                case SemanticBoolLiteral boolean:

                    output.AppendLine(
                        boolean.Value
                            ? "    lda #$01"
                            : "    lda #$00"
                    );

                    return;


                // -----------------------------------------------------
                // variable
                // -----------------------------------------------------

                case SemanticVariableReference variable:

                    output.AppendLine(
                        $"    lda {variable.StorageName}"
                    );

                    return;


                // -----------------------------------------------------
                // addition
                // -----------------------------------------------------

                case SemanticBinaryAdd add:

                    GenerateLoadValue(
                        output,
                        add.Left
                    );


                    // Save left operand on hardware stack.
                    output.AppendLine(
                        "    pha"
                    );


                    GenerateLoadValue(
                        output,
                        add.Right
                    );


                    output.AppendLine(
                        $"    sta {ExpressionTemp}"
                    );


                    // Restore left operand.
                    output.AppendLine(
                        "    pla"
                    );


                    output.AppendLine(
                        "    clc"
                    );


                    output.AppendLine(
                        $"    adc {ExpressionTemp}"
                    );


                    return;
                case SemanticBinarySubtract subtract:

                    GenerateLoadValue(
                        output,
                        subtract.Left
                    );

                    output.AppendLine(
                        "    pha"
                    );


                    GenerateLoadValue(
                        output,
                        subtract.Right
                    );

                    output.AppendLine(
                        $"    sta {ExpressionTemp}"
                    );


                    output.AppendLine(
                        "    pla"
                    );

                    // 6502 subtraction requires carry SET.
                    output.AppendLine(
                        "    sec"
                    );

                    output.AppendLine(
                        $"    sbc {ExpressionTemp}"
                    );

                    return;
                case SemanticBinaryBitwise bitwise:

                    GenerateLoadValue(
                        output,
                        bitwise.Left
                    );

                    output.AppendLine(
                        "    pha"
                    );


                    GenerateLoadValue(
                        output,
                        bitwise.Right
                    );

                    output.AppendLine(
                        $"    sta {ExpressionTemp}"
                    );


                    output.AppendLine(
                        "    pla"
                    );


                    switch (bitwise.Operator)
                    {
                        case SemanticBitwiseOperator.And:

                            output.AppendLine(
                                $"    and {ExpressionTemp}"
                            );

                            break;


                        case SemanticBitwiseOperator.Xor:

                            output.AppendLine(
                                $"    eor {ExpressionTemp}"
                            );

                            break;


                        case SemanticBitwiseOperator.Or:

                            output.AppendLine(
                                $"    ora {ExpressionTemp}"
                            );

                            break;
                    }

                    return;
                case SemanticShift shift:

                    // Preserve value being shifted.
                    GenerateLoadValue(
                        output,
                        shift.Left
                    );

                    output.AppendLine(
                        "    pha"
                    );


                    // Shift count -> X
                    GenerateLoadValue(
                        output,
                        shift.Right
                    );

                    output.AppendLine(
                        "    tax"
                    );


                    // Restore value -> A
                    output.AppendLine(
                        "    pla"
                    );


                    string shiftLoop =
                        NextLabel("shift_loop");

                    string shiftEnd =
                        NextLabel("shift_end");


                    // Shifting zero times means no change.
                    output.AppendLine(
                        "    cpx #$00"
                    );

                    output.AppendLine(
                        $"    beq {shiftEnd}"
                    );


                    output.AppendLine(
                        $"{shiftLoop}:"
                    );


                    if (
                        shift.Operator
                        == SemanticShiftOperator.Left
                    )
                    {
                        output.AppendLine(
                            "    asl a"
                        );
                    }
                    else
                    {
                        output.AppendLine(
                            "    lsr a"
                        );
                    }


                    output.AppendLine(
                        "    dex"
                    );

                    output.AppendLine(
                        $"    bne {shiftLoop}"
                    );


                    output.AppendLine(
                        $"{shiftEnd}:"
                    );

                    return;



                // -----------------------------------------------------
                // comparison
                // -----------------------------------------------------

                case SemanticComparison comparison:

                    GenerateComparison(
                        output,
                        comparison
                    );

                    return;


                // -----------------------------------------------------
                // method call returning a value
                // -----------------------------------------------------

                case SemanticMethodCallValue call:

                    GenerateCall(
                        output,
                        call.Call
                    );

                    // Return value is already in A.
                    return;


                default:

                    throw new Exception(
                        "Internal compiler error: " +
                        $"cannot generate value " +
                        $"'{value.GetType().Name}'."
                    );
            }
        }


        // =============================================================
        // Comparison
        //
        // Produces:
        //
        // A = 0   false
        // A = 1   true
        //
        // Comparisons are unsigned.
        // =============================================================

        private void GenerateComparison(
            StringBuilder output,
            SemanticComparison comparison
        )
        {
            string trueLabel =
                NextLabel("compare_true");

            string falseLabel =
                NextLabel("compare_false");

            string endLabel =
                NextLabel("compare_end");


            // Left side -> A
            GenerateLoadValue(
                output,
                comparison.Left
            );


            // Preserve left.
            output.AppendLine(
                "    pha"
            );


            // Right side -> A
            GenerateLoadValue(
                output,
                comparison.Right
            );


            // Preserve right.
            output.AppendLine(
                $"    sta {ExpressionTemp}"
            );


            // Restore left.
            output.AppendLine(
                "    pla"
            );


            // Compare:
            //
            // A = left
            // M = right
            output.AppendLine(
                $"    cmp {ExpressionTemp}"
            );


            switch (comparison.Operator)
            {
                // -----------------------------------------------------
                // ==
                // -----------------------------------------------------

                case SemanticComparisonOperator.Equal:

                    output.AppendLine(
                        $"    beq {trueLabel}"
                    );

                    break;


                // -----------------------------------------------------
                // !=
                // -----------------------------------------------------

                case SemanticComparisonOperator.NotEqual:

                    output.AppendLine(
                        $"    bne {trueLabel}"
                    );

                    break;


                // -----------------------------------------------------
                // <
                //
                // CMP clears carry when left < right.
                // -----------------------------------------------------

                case SemanticComparisonOperator.Less:

                    output.AppendLine(
                        $"    bcc {trueLabel}"
                    );

                    break;


                // -----------------------------------------------------
                // <=
                // -----------------------------------------------------

                case SemanticComparisonOperator.LessOrEqual:

                    output.AppendLine(
                        $"    bcc {trueLabel}"
                    );

                    output.AppendLine(
                        $"    beq {trueLabel}"
                    );

                    break;


                // -----------------------------------------------------
                // >
                // -----------------------------------------------------

                case SemanticComparisonOperator.Greater:

                    output.AppendLine(
                        $"    bcc {falseLabel}"
                    );

                    output.AppendLine(
                        $"    beq {falseLabel}"
                    );

                    output.AppendLine(
                        $"    jmp {trueLabel}"
                    );

                    break;


                // -----------------------------------------------------
                // >=
                // -----------------------------------------------------

                case SemanticComparisonOperator.GreaterOrEqual:

                    output.AppendLine(
                        $"    bcs {trueLabel}"
                    );

                    break;


                default:

                    throw new Exception(
                        "Internal compiler error: " +
                        "unknown comparison operator."
                    );
            }


            // ---------------------------------------------------------
            // FALSE
            // ---------------------------------------------------------

            output.AppendLine(
                $"{falseLabel}:"
            );

            output.AppendLine(
                "    lda #$00"
            );

            output.AppendLine(
                $"    jmp {endLabel}"
            );


            // ---------------------------------------------------------
            // TRUE
            // ---------------------------------------------------------

            output.AppendLine(
                $"{trueLabel}:"
            );

            output.AppendLine(
                "    lda #$01"
            );


            // ---------------------------------------------------------
            // END
            // ---------------------------------------------------------

            output.AppendLine(
                $"{endLabel}:"
            );
        }


        // =============================================================
        // Method calls
        // =============================================================

        private void GenerateCall(
            StringBuilder output,
            SemanticCall call
        )
        {
            for (
                int i = 0;
                i < call.Arguments.Count;
                i++
            )
            {
                GenerateLoadValue(
                    output,
                    call.Arguments[i]
                );


                output.AppendLine(
                    $"    sta {call.ParameterStorageNames[i]}"
                );
            }


            output.AppendLine(
                $"    jsr {call.TargetLabel}"
            );


            // Byte/bool return value, when applicable,
            // remains in A.
        }


        // =============================================================
        // Unique labels
        // =============================================================

        private string NextLabel(
            string prefix
        )
        {
            string label =
                $"__nesoop_{prefix}_{_labelCounter}";

            _labelCounter++;

            return label;
        }
    }
}